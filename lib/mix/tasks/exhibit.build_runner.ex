defmodule Mix.Tasks.Exhibit.BuildRunner do
  @shortdoc "Assembles priv/runner.exs from the modules in lib/"
  @moduledoc """
  Generates `priv/runner.exs`, the single-file script a target project runs
  with `MIX_ENV=test mix run priv/runner.exs NOTEBOOK`.

  The script is the concatenation of `Exhibit.Parser`, `Exhibit.Output` and
  `Exhibit.Runner`, renamed under `Exhibit.Runner.*` so nothing in a target
  project can collide with them, followed by a call to `main/1`.

      mix exhibit.build_runner            # writes priv/runner.exs
      mix exhibit.build_runner --out PATH # writes somewhere else

  The file is only rewritten when its content changes, so the escript (which
  embeds it as an `@external_resource`) is not needlessly recompiled.
  """

  use Mix.Task

  @default_out "priv/runner.exs"
  @sources ["lib/exhibit/parser.ex", "lib/exhibit/output.ex", "lib/exhibit/runner.ex"]

  @impl Mix.Task
  def run(args) do
    {opts, _, _} = OptionParser.parse(args, strict: [out: :string])
    out = Keyword.get(opts, :out, @default_out)
    content = source()

    if File.exists?(out) and File.read!(out) == content do
      Mix.shell().info("#{out} is up to date")
    else
      File.mkdir_p!(Path.dirname(out))
      File.write!(out, content)
      Mix.shell().info("wrote #{out}")
    end
  end

  @doc "The content of the generated runner."
  @spec source() :: String.t()
  def source do
    modules =
      @sources
      |> Enum.map(&File.read!/1)
      |> Enum.map_join("\n", &namespace/1)

    """
    # Generated by `mix exhibit.build_runner` from #{Enum.join(@sources, ", ")}.
    # Do not edit by hand. Runs inside a target project, with no dependency on
    # exhibit:
    #
    #     MIX_ENV=test mix run priv/runner.exs NOTEBOOK.livemd
    #
    # Evaluates every Elixir cell in order and writes Livebook-format outputs
    # back into the notebook. Exits 1 if a cell fails.

    #{modules}
    Exhibit.Runner.main(System.argv())
    """
  end

  defp namespace(code) do
    code
    |> String.replace(~r/\bExhibit\.Parser\b/, "Exhibit.Runner.Parser")
    |> String.replace(~r/\bExhibit\.Output\b/, "Exhibit.Runner.Output")
  end
end
